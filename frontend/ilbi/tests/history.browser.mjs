import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { createServer } from 'vite';
import { fileURLToPath } from 'node:url';
import { launchBrowser } from './browser/chrome.mjs';

const delay = ms => new Promise(resolve => setTimeout(resolve, ms));
let server, browser;
try {
  server = await createServer({ root:fileURLToPath(new URL('..',import.meta.url)),cacheDir:'node_modules/.vite-history-qa',optimizeDeps:{include:['react','react-dom/client','react-router-dom','lucide-react','qrcode']},logLevel:'error',server:{host:'127.0.0.1',port:0} });
  await server.listen();
  browser = await launchBrowser({ width:1440,height:1150 });
  await browser.call('Page.navigate',{url:`http://127.0.0.1:${server.httpServer.address().port}/tests/browser/history.html`});
  const wait = async expression => {
    for(let i=0;i<180;i++){if(await browser.evaluate(expression))return;await delay(40);}
    throw Error(`Timeout: ${expression}\n${browser.errors.join('\n')}`);
  };
  const clickText = text => browser.evaluate(`(()=>{const button=[...document.querySelectorAll('button')].find(node=>node.textContent.trim()===${JSON.stringify(text)});if(!button)throw Error('Missing button');button.click();})()`);
  const fill = async (selector,value) => {
    await browser.evaluate(`(()=>{const input=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,${JSON.stringify(value)});input.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  };
  const close = async () => {await browser.evaluate(`document.querySelector('dialog[open]').dispatchEvent(new Event('cancel',{bubbles:true,cancelable:true}))`);await wait('!document.querySelector("dialog[open]")');};
  const screenshot = async path => {const{data}=await browser.call('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});await writeFile(path,Buffer.from(data,'base64'));};
  await wait('document.querySelectorAll(".history-event").length===20');
  assert.equal(await browser.evaluate('document.querySelector(".sidebar a[href=\\"/history\\"]")?.textContent.trim()'), 'Tarix');
  assert.equal(await browser.evaluate('document.querySelector(".history-event").innerText.includes("Sotuv amalga oshirildi")'), true);
  assert.match(await browser.evaluate('document.querySelector(".history-feed").innerText'),/Bugun/);
  await screenshot('/tmp/ilbi-history-desktop.png');
  await browser.evaluate('document.querySelector(".history-event").click()');
  await wait('Boolean(document.querySelector("dialog[open] #history-receipt"))');
  assert.match(await browser.evaluate('document.querySelector("#history-receipt").innerText'),/Arabica qahva/);
  await clickText('80 mm');
  await wait('document.querySelector("#history-receipt").dataset.paperWidth==="80mm"');
  await clickText('A4 ko‘rinish');
  await wait('document.querySelectorAll("dialog[open]").length===2');
  assert.match(await browser.evaluate('[...document.querySelectorAll("dialog[open]")].at(-1).innerText'),/Arabica qahva/);
  await browser.evaluate(`[...document.querySelectorAll('dialog[open]')].at(-1).dispatchEvent(new Event('cancel',{cancelable:true}))`);
  await wait('document.querySelectorAll("dialog[open]").length===1');
  await screenshot('/tmp/ilbi-history-receipt.png');
  await close();
  await clickText('Ombor');
  await wait('document.querySelectorAll(".history-event").length===1');
  await browser.evaluate('document.querySelector(".history-event").click()');
  await wait('Boolean(document.querySelector("dialog[open] .history-fields"))');
  assert.match(await browser.evaluate('document.querySelector("dialog[open]").innerText'),/Faktura: 1248/);
  await close();
  await clickText('Katalog');
  await wait('document.querySelectorAll(".history-event").length===19');
  await browser.evaluate('document.querySelector(".history-event").click()');
  await wait('Boolean(document.querySelector(".history-change-values"))');
  assert.match(await browser.evaluate('document.querySelector(".history-change-values").innerText'),/Coca-Cola 1 L/);
  assert.match(await browser.evaluate('document.querySelector(".history-change-values").innerText'),/Coca-Cola 1.5 L/);
  await close();
  await clickText('Barcha amallar');
  await wait('document.querySelectorAll(".history-event").length===20');
  await browser.evaluate('document.querySelector("button[title=\\"Keyingi sahifa\\"]").click()');
  await wait('document.querySelectorAll(".history-event").length===4');
  await fill('input[aria-label="Tarixdan qidirish"]','Madina');
  await wait('document.querySelectorAll(".history-event").length===2');
  await fill('input[aria-label="Tarixdan qidirish"]','topilmaydigan_qidiruv');
  await wait('document.body.innerText.includes("Mos amallar topilmadi")');
  await clickText('Filtrlarni tozalash');
  await wait('document.querySelectorAll(".history-event").length===20');
  await browser.evaluate('document.querySelector("[aria-label=\\"Tarix davri\\"][aria-haspopup]").click()');
  await wait('Boolean(document.querySelector(".custom-select-menu input"))');
  await fill('.custom-select-menu input','Bugun');
  await wait('document.querySelectorAll(".custom-select-menu [role=option]").length===1');
  await browser.evaluate('document.querySelector(".custom-select-menu [role=option]").click()');
  await wait('document.querySelectorAll(".history-event").length===4');
  // The route retains no open detail when the owner switches shops.
  await browser.evaluate('historyQA.holdDetail=true;document.querySelector(".history-event").click()');
  await wait('historyQA.pending.length===1');
  await browser.evaluate('historyQA.select(8)');
  await wait('document.body.innerText.includes("IKKINCHI_DOKON_TOVARI")&&!document.querySelector("dialog[open]")');
  await browser.evaluate('historyQA.pending.shift()()');
  await delay(100);
  assert.equal(await browser.evaluate('Boolean(document.querySelector("dialog[open]"))'),false);
  await browser.evaluate('historyQA.select(7)');
  await wait('document.querySelectorAll(".history-event").length===20');
  await browser.evaluate('historyQA.failList=true;window.dispatchEvent(new Event("focus"))');
  await wait('document.body.innerText.includes("Tarixni yuklab bo‘lmadi")');
  await browser.evaluate('historyQA.failList=false');
  await clickText('Qayta urinish');
  await wait('document.querySelectorAll(".history-event").length===20');
  await browser.evaluate('document.documentElement.setAttribute("data-theme","dark")');
  await screenshot('/tmp/ilbi-history-dark.png');
  await browser.resize(390,900);
  await delay(150);
  assert.equal(await browser.evaluate('document.documentElement.scrollWidth<=innerWidth'),true,'History page must fit mobile viewport');
  await screenshot('/tmp/ilbi-history-mobile.png');
  await browser.evaluate('document.querySelector(".history-event").click()');
  await wait('Boolean(document.querySelector("dialog[open] #history-receipt"))');
  await delay(80);
  assert.equal(await browser.evaluate('document.querySelector("dialog[open] .dialog-content").scrollWidth<=document.querySelector("dialog[open] .dialog-content").clientWidth+1'),true,'Receipt detail must fit mobile dialog');
  await close();
  assert.deepEqual(browser.errors,[]);
  console.log('PASS history sidebar, timeline, receipt/A4, intake and edit details, search/date/category filters, pagination, error recovery, tenant isolation, light/dark/mobile.');
} finally {
  if(browser)await browser.close();
  if(server)await server.close();
}
